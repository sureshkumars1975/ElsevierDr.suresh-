export const slugify = (title) =>
  title
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const make = (title, subject, scope, model, slug) => {
  const s = slug || slugify(title);
  return {
    id: s,
    title,
    subject,
    scope,
    model,
    url: `https://www.sciencedirect.com/journal/${s}`,
    guideUrl: `https://www.sciencedirect.com/journal/${s}/publish/guide-for-authors`,
  };
};

export const journals = [
  ...Object.entries(groups).flatMap(([subject, list]) =>
    list.map(([title, scope, slug]) => make(title, subject, scope, SUBSCRIPTION, slug)),
  ),
  ...sponsored.map(([subject, title, scope]) => make(title, subject, scope, SPONSORED)),
].sort((a, b) => a.title.localeCompare(b.title));

export const subjects = [...new Set(journals.map((j) => j.subject))].sort();
export const models = [SUBSCRIPTION, SPONSORED];
